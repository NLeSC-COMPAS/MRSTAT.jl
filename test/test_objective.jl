# Consistency tests for the objective, run for BOTH forward models on a
# small hand-built problem (8×8 image, 64 voxels; the number of
# phase-encode cycles adapts so K·N matches each model's echo count).
# Small enough that every check runs in milliseconds, complete enough to
# exercise the full objective (forward model, phase encoding, signal
# integration, Jᴴv gradient, Gauss-Newton operator).
#
# The finite-difference gradient check is the regression test for the class
# of bug found during the surrogate integration: the Jv/Jᴴv kernels and
# BlochSimulators' signal path must implement the same k-space phase
# convention (exp(-i·k·x) since BlochSimulators 357746b), or the analytic
# gradient stops being the derivative of the actual cost. That bug drove
# the FD/analytic ratio to ≈ -1 and made the "descent" direction ascend.
# The check runs at a NON-uniform parameter vector — at a uniform one the
# inconsistency is nearly symmetric and can escape detection (which is how
# it originally went unnoticed).

using Test
using CUDA
using Random
using LinearAlgebra: dot, norm
using StructArrays: StructArray
using BlochSimulators
using ComputationalResources: CUDALibs

# Build the complete small experiment for one model: geometry, ground-truth
# parameter vector, raw data generated by the model itself, and the
# objective closure. `ratio_window` is the accepted FD/analytic band (see
# the per-model notes at the call sites).
function objective_consistency_tests(model, label; ratio_window)
    @testset "objective consistency: $label" begin
        Nimg = 8
        nvox = Nimg^2
        nTR = nechos(model)
        K, rem = divrem(nTR, Nimg)
        @test rem == 0   # the geometries below are chosen to divide evenly

        FOV = 22.4
        Δxy = FOV / Nimg
        xs = collect(-FOV/2:Δxy:FOV/2-Δxy)
        coordinates = gpu(f32(vec(@coordinates xs xs [0.0])))
        py = repeat(-Nimg÷2:Nimg÷2-1, K)
        Δk = 2π / FOV
        k_start = [(-Nimg / 2 * Δk) + im * (py[r] * Δk) for r in 1:nTR]
        trajectory = gpu(f32(CartesianTrajectory2D(nTR, Nimg, 5e-6, k_start, Δk, py, 1)))
        coils = gpu(f32(complex.(reshape(collect(LinRange(0.8, 1.2, nvox)), nvox, 1))))

        # Ground truth: distinct voxels inside both models' validity boxes,
        # asymmetric ρ, stacked as the solver stacks them.
        rng = Xoshiro(2026)
        T₁t = exp.(rand(rng, nvox) .* (log(2.5) - log(0.3)) .+ log(0.3))
        T₂t = min.(exp.(rand(rng, nvox) .* (log(0.25) - log(0.03)) .+ log(0.03)), 0.8 .* T₁t)
        transmit_field = Float32.(0.9 .+ 0.2 .* rand(rng, nvox))
        x_true = Float32.(vec([log.(T₁t) log.(T₂t) (0.6 .+ 0.8 .* rand(rng, nvox)) (rand(rng, nvox) .- 0.5)]))

        # Raw data from the same forward path the objective uses.
        params_true = gpu(f32(MRSTAT.optim_to_physical_pars(x_true, transmit_field)))
        echos_true = compute_echos(model, params_true)
        phase_encoding!(echos_true, trajectory, coordinates)
        raw = magnetization_to_signal(CUDALibs(), echos_true, params_true, trajectory,
                                      coordinates, coils)

        obj(x, mode) = MRSTAT.objective(Float32.(x), CUDALibs(), mode, raw, model,
                                        coordinates, coils, trajectory, transmit_field)

        # A perturbed evaluation point shared by the checks below.
        x_eval = x_true .+ 0.1f0 .* randn(rng, Float32, length(x_true))

        # --- cost consistency -------------------------------------------
        # At the generating parameters the residual is a recomputation of
        # the same deterministic path — the cost is (numerically) zero.
        f_true, _ = obj(x_true, 0)
        @test f_true ≤ 1e-6
        # Mode 0 and mode 2 must price the same point identically.
        f0, _ = obj(x_eval, 0)
        f2, _, g, H = obj(x_eval, 2)
        @test f0 == f2
        @test all(isfinite, g)

        # --- gradient vs central finite differences, per block ----------
        n = nvox
        for (name, idx) in pairs((T₁ = 1:n, T₂ = n+1:2n, ρˣ = 2n+1:3n, ρʸ = 3n+1:4n))
            d = zeros(Float32, 4n)
            d[idx] = -g[idx]
            nd = norm(d)
            @test nd > 0
            d ./= nd
            ε = 1f-3
            fd = (obj(x_eval .+ ε .* d, 0)[1] - obj(x_eval .- ε .* d, 0)[1]) / 2ε
            pred = dot(g, d)
            # The single most important assertion: moving along the
            # analytic descent direction must actually decrease the cost —
            # precisely what the k-space sign bug broke.
            @test fd < 0
            @test first(ratio_window) ≤ fd / pred ≤ last(ratio_window)
        end

        # --- Gauss-Newton operator is symmetric PSD ----------------------
        # Steihaug-CG relies on H = Re(JᴴJ) being real-symmetric positive
        # semidefinite; equivalently, Jᴴv is the adjoint of Jv on the real
        # parametrization.
        u = randn(rng, length(g))
        w = randn(rng, length(g))
        Hu, Hw = H * u, H * w
        @test isapprox(dot(u, Hw), dot(w, Hu); rtol = 1e-4)   # symmetry
        @test dot(u, Hu) ≥ -1e-6 * norm(u) * norm(Hu)         # PSD (float slack)
        @test dot(w, Hw) ≥ -1e-6 * norm(w) * norm(Hw)
    end
    return nothing
end

# BlochModel: cost and gradient come from the same simulator, so the
# FD/analytic ratio is tight (limited only by FD truncation and Float32).
let nTR = 8 * 8
    RF = complex.(collect(range(1, 90; length = nTR)))
    bloch = BlochModel(gpu(f32(FISP2D(RF, ones(nTR, 1) .|> complex, 0.010, 0.006, 32, 0.025))))
    objective_consistency_tests(bloch, "BlochModel"; ratio_window = (0.9, 1.1))
end

# SurrogateModel: the T₁/T₂ gradient comes from the derivative
# sub-networks — trained approximations rather than exact derivatives of
# the signal sub-network — so per-direction deviations of around 10% are a
# property of the model itself at this voxel count (they average out at
# reconstruction size: 0.95–1.01 at 14 400 voxels). The failure modes this
# test guards against land far outside the window anyway: a sign flip
# gives ≈ -1, wrong units or a transposed layout give ≈ 0 or ≫ 1.
objective_consistency_tests(SURROGATE, "SurrogateModel"; ratio_window = (0.75, 1.25))

# End-to-end comparison of the two forward models: accuracy and speed of a
# complete MR-STAT reconstruction with the neural surrogate vs the Bloch
# simulator.
#
# Run with:
#   source ../NeuralBloch.jl/env.sh        # binds PythonCall to the torch venv
#   julia --project=. scripts/compare_models.jl
#
# Design:
# - ONE experiment for both arms: the same 120×120 phantom, geometry, coils
#   and B₁ map, and the same physics — the Bloch arm simulates the FISP3D
#   sequence the surrogate was trained on (RF train + constants from the
#   sibling NeuralBloch repository), so the two forward models describe the
#   same acquisition.
# - Each arm reconstructs raw data generated by its own forward model, so
#   each arm is exactly self-consistent: the Bloch arm shows the
#   solver-limit accuracy (data and reconstruction share the simulator —
#   the classic inverse-crime baseline), and the surrogate arm shows what
#   the network's approximation error adds on top.
# - Both arms run through the same solver with the same bounds (the
#   surrogate's trained box — harmlessly tighter than the physical box for
#   the Bloch arm, and it makes the two searches identical) and the same
#   instrumented objective wrapper, so per-call timings are comparable.
#   The solver+objective are composed directly here (the same lines
#   mrstat_recon runs) so the objective can be wrapped for timing without
#   touching the package.
# - Nothing is timed until a throwaway warm-up solve has run with each
#   model. The first reconstruction of a session pays one-off JIT
#   compilation for machinery both arms share — Jᴴv in the first mode-2
#   objective call, Jv in the first CG product — measured here at ~17 s.
#   That is enough to make whichever arm runs first look 1.5× slower
#   end-to-end than the other, and to inflate its "time inside the
#   objective" past the arm whose every individual call is 6× slower. The
#   cost belongs to the session, not to a forward model (both models hand
#   the kernels the same concrete types, so the kernels compile once and
#   whoever goes first is billed), so it is paid before the clock starts.
#
# Speed is reported at three levels because they answer different questions:
#   1. forward model alone      — what the surrogate accelerates (~50×);
#   2. per objective call       — how much of one solver step that is;
#   3. end-to-end wall          — what the user experiences. Both arms share
#      the Gauss-Newton Jv/Jᴴv cost, which dominates each solver iteration,
#      so by Amdahl's law the end-to-end ratio is far below the
#      forward-model ratio. Reporting only one of these numbers would
#      mislead in one direction or the other.

ENV["MPLBACKEND"] = "Agg"   # matplotlib without a display; must precede PythonPlot

using MRSTAT
using MRSTAT.TrustRegionReflective: SolverOptions, solver
using BlochSimulators
using ComputationalResources: CUDALibs
using CUDA
using StructArrays
using Statistics
using Printf
using Logging: NullLogger, with_logger
using PythonPlot

const OUTDIR = joinpath(@__DIR__, "output")
mkpath(OUTDIR)

# ---------------------------------------------------------------------------
# The two forward models over the same physics
# ---------------------------------------------------------------------------

surrogate = load_surrogate()

# The training sequence, reproduced from NeuralBloch's data_generation.jl +
# config/data.yaml (frozen for this checkpoint): FISP3D with the repo's RF
# train, TR 5.58 ms, TE 2.745 ms, max_state 64, TI 10.84 ms, TW 0, five
# repetitions (sampling the last), inversion prepulse, wait spoiling.
neuralbloch_dir = joinpath(dirname(pkgdir(MRSTAT)), "NeuralBloch")
readvec(p) = [parse(Float64, l) for l in eachline(p) if !isempty(strip(l))]
flip_deg = readvec(joinpath(neuralbloch_dir, "data", "rf_data", "rf_angle_list.txt"))
phase_deg = readvec(joinpath(neuralbloch_dir, "data", "rf_data", "rf_phase_list.txt"))
rf_train = flip_deg .* exp.(1im .* deg2rad.(phase_deg))
sequence = gpu(f32(FISP3D(rf_train, 0.00558, 0.002745, 64, 0.01084, 0.000, 5, true, true, 1, 0.0)))
bloch = BlochModel(sequence)
@assert nechos(bloch) == nechos(surrogate) == 600

# ---------------------------------------------------------------------------
# One experiment, two raw-data sets (one per forward model)
# ---------------------------------------------------------------------------

raw_sur, coordinates, coils, trajectory, transmit_field, phantom =
    generate_synthetic_data(surrogate)
N = isqrt(length(coordinates))

# The Bloch arm's raw data: same phantom and geometry, echos from the
# simulator instead of the network.
params_true = StructArray{T₁T₂B₁ρˣρʸ{Float32}}((
    phantom.T₁, phantom.T₂, gpu(f32(vec(transmit_field))), phantom.ρˣ, phantom.ρʸ))
echos_bloch = compute_echos(bloch, params_true)
phase_encoding!(echos_bloch, trajectory, coordinates)
raw_bloch = magnetization_to_signal(CUDALibs(), echos_bloch, params_true, trajectory,
                                    coordinates, coils)

T₁true = Array(phantom.T₁)
T₂true = Array(phantom.T₂)
ρtrue = abs.(complex.(Array(phantom.ρˣ), Array(phantom.ρʸ)))

# ---------------------------------------------------------------------------
# Instrumented reconstruction (the same composition mrstat_recon performs,
# with a timing wrapper around the objective)
# ---------------------------------------------------------------------------

function instrumented_recon(model, raw; x0, LB, UB, options = SolverOptions())
    check_experiment(model, trajectory, transmit_field)
    nvox = length(coordinates)
    x0m = repeat(x0', nvox) |> f32
    LBm = repeat(LB', nvox) |> f32
    UBm = repeat(UB', nvox) |> f32
    resource = CUDALibs()

    calls = NamedTuple{(:mode, :seconds),Tuple{Int,Float64}}[]
    objfun = (x, mode) -> begin
        t0 = time()
        result = MRSTAT.objective(x, resource, mode, raw, model, coordinates,
                                  coils, trajectory, transmit_field)
        push!(calls, (mode = mode, seconds = time() - t0))
        result
    end

    wall = @elapsed output = solver(objfun, vec(x0m), vec(LBm), vec(UBm),
                                    options, (x, t) -> nothing)
    return output, calls, wall
end

function report_accuracy(output, label)
    xm = reshape(output.x[:, end], :, 4)
    T₁ = exp.(xm[:, 1]); T₂ = exp.(xm[:, 2])
    ρ = abs.(complex.(xm[:, 3], xm[:, 4]))
    relerr(a, b) = 100 * median(abs.(a .- b) ./ abs.(b))
    p95err(a, b) = 100 * quantile(abs.(a .- b) ./ abs.(b), 0.95)
    @printf("  %-24s %10s %10s\n", label, "median", "p95")
    @printf("    %-22s %9.3f%% %9.3f%%\n", "T₁ error", relerr(T₁, T₁true), p95err(T₁, T₁true))
    @printf("    %-22s %9.3f%% %9.3f%%\n", "T₂ error", relerr(T₂, T₂true), p95err(T₂, T₂true))
    @printf("    %-22s %9.3f%% %9.3f%%\n", "|ρ| error", relerr(ρ, ρtrue), p95err(ρ, ρtrue))
    return (T₁ = T₁, T₂ = T₂, ρ = ρ)
end

function save_maps(T₁, T₂, ρ, label)
    fig, axs = subplots(1, 3; figsize = (13, 4))
    for (ax, img, ttl, vmax) in zip(axs, (T₁, T₂, ρ), ("T₁ (s)", "T₂ (s)", "|ρ|"),
                                    (2.6, 0.25, 1.6))
        im = ax.imshow(reshape(img, N, N); vmin = 0, vmax = vmax, cmap = "viridis")
        ax.set_title("$ttl — $label"); ax.axis("off")
        fig.colorbar(im; ax = ax, fraction = 0.046)
    end
    fig.tight_layout()
    path = joinpath(OUTDIR, "compare_$(replace(label, ' ' => '_')).png")
    fig.savefig(path; dpi = 150)
    PythonPlot.pyplot.close(fig)
    return path
end

# ---------------------------------------------------------------------------
# Speed level 1: the forward model alone (echos + derivatives, warmed)
# ---------------------------------------------------------------------------

println("═"^72)
println("Speed level 1: forward model alone ($(length(params_true)) voxels)")
println("═"^72)
compute_echos_and_derivatives(surrogate, params_true); CUDA.synchronize()
t_fwd_sur = CUDA.@elapsed compute_echos_and_derivatives(surrogate, params_true)
compute_echos_and_derivatives(bloch, params_true); CUDA.synchronize()
t_fwd_blo = CUDA.@elapsed compute_echos_and_derivatives(bloch, params_true)
@printf("  surrogate : %8.1f ms\n", 1000t_fwd_sur)
@printf("  Bloch     : %8.1f ms\n", 1000t_fwd_blo)
@printf("  ratio     : %8.1f×\n", t_fwd_blo / t_fwd_sur)

# ---------------------------------------------------------------------------
# The two reconstructions (same bounds: the surrogate's trained box)
# ---------------------------------------------------------------------------

x0, LB, UB = default_bounds(surrogate)

# Compile the shared solver machinery before anything is measured (see the
# header). Two trust-region iterations are plenty: the first alone
# exercises the mode-2 objective, Jᴴv, Jv (through the first CG product),
# chooseStep and the mode-0 objective. Both models are warmed, so neither
# arm carries residual model-specific specialization into its measurement.
# The solver is chatty and none of this is a result, so its output goes to
# devnull and its @info/@time chatter to a null logger.
function warmup!(model, raw)
    redirect_stdout(devnull) do
        with_logger(NullLogger()) do
            instrumented_recon(model, raw; x0, LB, UB,
                               options = SolverOptions(max_iter_trf = 2))
        end
    end
    return nothing
end

println("═"^72)
println("Warm-up: compiling the shared Jv/Jᴴv and solver machinery (untimed)")
println("═"^72)
t_warm = @elapsed begin
    warmup!(surrogate, raw_sur)
    warmup!(bloch, raw_bloch)
end
@printf("  done in %.1f s — compilation only, excluded from every number below.\n", t_warm)

println("═"^72)
println("Reconstruction A: SurrogateModel (self-consistent data)")
println("═"^72)
out_sur, calls_sur, wall_sur = instrumented_recon(surrogate, raw_sur; x0, LB, UB)

println("═"^72)
println("Reconstruction B: BlochModel (self-consistent data — inverse-crime baseline)")
println("═"^72)
out_blo, calls_blo, wall_blo = instrumented_recon(bloch, raw_bloch; x0, LB, UB)

# ---------------------------------------------------------------------------
# Report
# ---------------------------------------------------------------------------

println("═"^72)
println("Accuracy vs the ground-truth phantom")
println("═"^72)
maps_sur = report_accuracy(out_sur, "surrogate")
maps_blo = report_accuracy(out_blo, "Bloch")
Δ = 100 * median(abs.(maps_sur.T₁ .- maps_blo.T₁) ./ maps_blo.T₁)
@printf("  arm-vs-arm: median |T₁(surrogate) − T₁(Bloch)| / T₁(Bloch) = %.3f%%\n", Δ)

save_maps(T₁true, T₂true, ρtrue, "ground truth")
save_maps(maps_sur..., "surrogate")
save_maps(maps_blo..., "Bloch")
println("  maps written to $OUTDIR")

println("═"^72)
println("Speed levels 2 and 3")
println("═"^72)
# Medians, not means: the first call of each mode carries one-off kernel
# compilation, and Julia GC pauses (tensor wrappers being collected) land
# inside whichever call is running — both would distort a 20-sample mean.
level2(calls, mode) = 1000 * median([c.seconds for c in calls if c.mode == mode])
count_mode(calls, mode) = count(c -> c.mode == mode, calls)
objtotal(calls) = sum(c.seconds for c in calls)
@printf("  %-36s %12s %12s\n", "", "surrogate", "Bloch")
@printf("  %-36s %10.1f ms %10.1f ms\n", "median mode-0 objective call", level2(calls_sur, 0), level2(calls_blo, 0))
@printf("  %-36s %10.1f ms %10.1f ms\n", "median mode-2 objective call", level2(calls_sur, 2), level2(calls_blo, 2))
@printf("  %-36s %9d/%-3d %8d/%-3d\n", "objective calls (mode 0/mode 2)",
        count_mode(calls_sur, 0), count_mode(calls_sur, 2),
        count_mode(calls_blo, 0), count_mode(calls_blo, 2))
# Guard against the confound the warm-up exists to remove: with everything
# compiled, the total time inside the objective is just the per-call
# medians times the call counts. A total that runs well above that means
# one call absorbed something which is not forward-model work — leftover
# compilation, a GC pause — so the two lines are printed together instead
# of leaving the reader to multiply the rows above and notice the gap.
medianfit(calls) = sum(count_mode(calls, m) * level2(calls, m) / 1000 for m in (0, 2))
@printf("  %-36s %10.1f s  %10.1f s\n", "time inside the objective (total)", objtotal(calls_sur), objtotal(calls_blo))
@printf("  %-36s %10.1f s  %10.1f s\n", "  └ expected: medians × call counts", medianfit(calls_sur), medianfit(calls_blo))
@printf("  %-36s %10.1f s  %10.1f s\n", "time in solver internals (H·v, CG)", wall_sur - objtotal(calls_sur), wall_blo - objtotal(calls_blo))
@printf("  %-36s %10.1f s  %10.1f s\n", "end-to-end reconstruction", wall_sur, wall_blo)
println()
# What the surrogate actually buys end-to-end, against what any
# forward-model acceleration could buy. The bound removes the surrogate
# arm's whole objective time, so it is generous — that time also contains
# the phase encoding, signal integration and Jᴴv gradient both arms pay.
@printf("  %-36s %10.2f×\n", "end-to-end speedup (surrogate)", wall_blo / wall_sur)
@printf("  %-36s %10.2f×\n", "  └ upper bound, free forward model",
        wall_blo / (wall_sur - objtotal(calls_sur)))
println()
println("  Reading the numbers: the surrogate makes the forward model ~",
        round(Int, t_fwd_blo / t_fwd_sur), "× faster, which shows directly in the")
println("  objective calls. End-to-end walls are dominated by the solver internals —")
println("  the Steihaug-CG Gauss-Newton products (Jv/Jᴴv), identical machinery in")
println("  both arms — so by Amdahl's law the end-to-end gain is limited to the")
println("  forward model's share of an iteration. The two walls are also not a pure")
println("  forward-model comparison: each arm reconstructs its own data, so the")
println("  solver may take different CG paths. The forward-model ratio (level 1) is")
println("  the gain available to any solver whose iteration cost is dominated by")
println("  simulation.")

println()
println("compare_models finished")
